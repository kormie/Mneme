/**
 * Serialize the Lean-shaped projection of spec/kernel.json into
 * bend/KernelIR.bend: a `K.Kernel` literal for the Bend verification layer
 * (bend/Decidable.bend proves `laws` over it in bend/LAWS.bend).
 *
 * This is the Bend counterpart of `lean-export.ts`: the same projection
 * (`projectKernel`), the same fields, nothing added or reinterpreted. The
 * emitted file is committed so `bend PROOF.bend` needs no Bun; the helix
 * test suite regenerates it and fails on any byte drift. Run:
 *
 *   bun src/bend-export.ts          # rewrites ../bend/KernelIR.bend
 *
 * Lean remains the certificate of record (AGENTS.md law 6). The Bend result
 * is a second, independent check of the same IR, not a certificate.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";
import { loadKernel } from "./kernel.js";
import {
  projectKernel,
  type LeanEdge,
  type LeanGraph,
  type LeanKernel,
  type LeanNode,
  type LeanPort,
} from "./lean-kernel.js";

const HERE = dirname(fileURLToPath(import.meta.url));
export const KERNEL_IR_BEND_PATH = resolve(HERE, "../../bend/KernelIR.bend");

/**
 * Bend string literal. The IR is plain printable ASCII; fail closed on
 * anything else (control characters, quotes, backslashes, non-ASCII) rather
 * than guess at Bend's escaping rules.
 */
function str(s: string): string {
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (c < 0x20 || c > 0x7e || ch === '"' || ch === "\\") {
      throw new Error(`unsupported character in IR string: ${JSON.stringify(s)}`);
    }
  }
  return `"${s}"`;
}

function strList(xs: string[]): string {
  return `[${xs.map(str).join(", ")}]`;
}

/** `pg-s2w` -> `graph_pg_s2w`. Fails on a name collision or a bad id. */
export function graphDefName(id: string): string {
  if (!/^[a-z][a-z0-9-]*$/.test(id)) {
    throw new Error(`graph id cannot name a Bend def: ${JSON.stringify(id)}`);
  }
  return `graph_${id.replace(/-/g, "_")}`;
}

function port(p: LeanPort): string {
  return `K.Port{${str(p.name)}, ${str(p.type)}, ${p.dir === "in" ? "K.DirIn{}" : "K.DirOut{}"}}`;
}

function node(n: LeanNode): string {
  const kind = n.kind === "prompt" ? "K.Prompt{}" : "K.Transform{}";
  const ports = n.ports.length === 0 ? "[]" : `[${n.ports.map(port).join(", ")}]`;
  return `K.Node{${str(n.id)}, ${kind}, ${ports}}`;
}

function edge(e: LeanEdge): string {
  const kind = e.kind === "data" ? "K.DataEdge{}" : "K.ControlEdge{}";
  const cyclic = e.cyclic ? "True{}" : "False{}";
  return `K.Edge{${str(e.id)}, ${str(e.from)}, ${str(e.to)}, ${str(e.fromPort)}, ${str(e.toPort)}, ${kind}, ${cyclic}, ${str(e.guard)}}`;
}

/** A Bend list literal, one item per line; `comma` trails the closing bracket. */
function listBlock(items: string[], indent: string, comma: boolean): string[] {
  const tail = comma ? "," : "";
  if (items.length === 0) return [`${indent}[]${tail}`];
  const lines = [`${indent}[`];
  items.forEach((it, i) => {
    lines.push(`${indent}  ${it}${i < items.length - 1 ? "," : ""}`);
  });
  lines.push(`${indent}]${tail}`);
  return lines;
}

function graphDef(g: LeanGraph): string[] {
  return [
    `def ${graphDefName(g.id)}() -> K.Graph:`,
    "  K.Graph{",
    `    ${str(g.id)},`,
    ...listBlock(g.nodes.map(node), "    ", true),
    ...listBlock(g.edges.map(edge), "    ", true),
    `    ${str(g.version)}`,
    "  }",
  ];
}

export function renderKernelBend(k: LeanKernel): string {
  const names = k.graphs.map((g) => graphDefName(g.id));
  if (new Set(names).size !== names.length) {
    throw new Error("two graph ids map to the same Bend def name");
  }

  const out: string[] = [];
  const push = (line: string): void => {
    out.push(line);
  };

  push("# GENERATED by `cd helix && bun src/bend-export.ts` from spec/kernel.json.");
  push("# Do not edit by hand; helix/test/bend-export.spec.ts enforces byte parity.");
  push("#");
  push("# Projection of the mneme.spec/0.10 kernel IR onto bend/Kernel.bend's");
  push("# `K.Kernel`, the same projection proofs/KernelIR.lean uses: ids, kinds,");
  push("# ports, edges, twins, frozen, layers. Prompt bodies are not in the IR and");
  push("# are not here (G2). IR fields with no counterpart are dropped: node");
  push("# labels/roles/signatures/bodyHash/promptRefs, edge `xor`, graph");
  push("# code/purpose/state/runtime, ingress, fuel, artifact metadata beyond");
  push("# `version`, layer idx/name, twin `never` prose, and the audit policy.");
  push("#");
  push("# `bend PROOF.bend` proves `Decidable.laws` over `kernel()` (LAWS.bend). That");
  push("# is a second check of the STATIC gate only: IR-checked, not MNEME-complete,");
  push("# and not a certificate. Lean's KernelIR.certificate is the artifact of record.");
  push("import Base");
  push("import ./Kernel.bend as K");
  push("");

  for (const g of k.graphs) {
    for (const line of graphDef(g)) push(line);
    push("");
  }

  const layers = k.layers.map(
    (l) => `K.Layer{${str(l.id)}, ${strList(l.stores)}, ${strList(l.graphIds)}}`,
  );
  const twins = k.twins.map(
    (t) => `K.Twin{${str(t.id)}, ${t.origin === "seed" ? "K.Seed{}" : "K.Discovered{}"}}`,
  );
  push("def kernel() -> K.Kernel:");
  push("  K.Kernel{");
  push(`    ${str(k.spec)},`);
  for (const line of listBlock(layers, "    ", true)) push(line);
  for (const line of listBlock(names.map((n) => `${n}()`), "    ", true)) push(line);
  for (const line of listBlock(twins, "    ", true)) push(line);
  push(`    ${strList(k.frozen)}`);
  push("  }");
  return out.join("\n") + "\n";
}

export function writeKernelBend(path: string = KERNEL_IR_BEND_PATH): string {
  const text = renderKernelBend(projectKernel(loadKernel()));
  writeFileSync(path, text);
  return path;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const path = writeKernelBend();
  console.log(`wrote ${path}`);
}
